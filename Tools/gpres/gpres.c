/***********************************************************************
 * gpres.c -- resource numbers of a geode for C code made by goc -cg.
 *
 * Usage:  gpres [-o OUT.h] GEODE.gp [FILE.goc...]
 *
 * goc -cg refers to the resources of a geode as GOCR_RES_<NAME> (the
 * name in upper case).  This program numbers them like glue does: first
 * the "resource" lines of the geode parameter file in their order, then
 * the resources the .goc files start (@start) but the .gp file does not
 * list, in the order of the files and of their @start lines (those of
 * the local files a .goc file includes, @include "...", where it
 * includes them).  Numbers start at 2 (0 is the core block, 1 the fixed
 * data, as in the 16-bit geode format).  The header goes to OUT.h or to
 * standard output.  See Port32/ABI.md.
 ***********************************************************************/
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

#include "gpscan.h"

static void
Usage(void)
{
    fprintf(stderr, "Usage: gpres [-o OUT.h] GEODE.gp [FILE.goc...]\n");
    exit(1);
}

static void
AddName(GpList *names, const char *name)
{
    char *up = GpUpper(name);

    if (GpListFind(names, up) < 0) {
	GpListAdd(names, up);
    }
    free(up);
}

int
main(int argc, char **argv)
{
    const char	*out = NULL;
    GpList	names = {NULL, 0, 0};
    FILE	*f = stdout;
    int		first = 1, i, j;
    size_t	n;

    if (argc >= 3 && strcmp(argv[1], "-o") == 0) {
	out = argv[2];
	first = 3;
    }
    if (first >= argc) {
	Usage();
    }
    n = strlen(argv[first]);
    if (n < 3 || !GpEqualNoCase(argv[first] + n - 3, ".gp")) {
	Usage();
    }
    for (i = first; i < argc; i++) {
	if (i == first) {
	    char    *text = GpMustRead(argv[i]);
	    GpList  found = {NULL, 0, 0};

	    GpResources(text, &found);
	    for (j = 0; j < found.count; j++) {
		AddName(&names, found.item[j]);
	    }
	    free(text);
	} else {
	    GpStarts starts = {NULL, 0, 0};

	    GpGocStarts(argv[i], &starts);
	    for (j = 0; j < starts.count; j++) {
		AddName(&names, starts.item[j].name);
	    }
	}
    }
    if (out != NULL && (f = fopen(out, "w")) == NULL) {
	perror(out);
	return 1;
    }
    fprintf(f, "/* generated by gpres from");
    for (i = first; i < argc; i++) {
	fprintf(f, " %s", GpBaseName(argv[i]));
    }
    fprintf(f, " */\n");
    for (i = 0; i < names.count; i++) {
	char *p;

	for (p = names.item[i]; *p != '\0'; p++) {
	    if (!isalnum((unsigned char) *p) && *p != '_') {
		*p = '_';
	    }
	}
	fprintf(f, "#define GOCR_RES_%s %d\n", names.item[i],
		GP_FIRST_RESOURCE + i);
    }
    if (out != NULL && fclose(f) != 0) {
	perror(out);
	return 1;
    }
    return 0;
}
