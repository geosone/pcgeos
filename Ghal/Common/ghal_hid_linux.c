/*
 * ghal_hid_linux.c -- Linux input key codes (KEY_*, linux/input-event-
 * codes.h) to HID keyboard usages (page 0x07).  X servers with the evdev
 * key codes (every current one) give the Linux code + 8; fbdev with
 * evdev will give it directly.
 */
#include "ghal_hid.h"

static const uint8_t linuxToHid[128] = {
    /*   0 */ 0x00, 0x29, 0x1e, 0x1f, 0x20, 0x21, 0x22, 0x23,
    /*   8 */ 0x24, 0x25, 0x26, 0x27, 0x2d, 0x2e, 0x2a, 0x2b,
    /*  16 */ 0x14, 0x1a, 0x08, 0x15, 0x17, 0x1c, 0x18, 0x0c,
    /*  24 */ 0x12, 0x13, 0x2f, 0x30, 0x28, 0xe0, 0x04, 0x16,
    /*  32 */ 0x07, 0x09, 0x0a, 0x0b, 0x0d, 0x0e, 0x0f, 0x33,
    /*  40 */ 0x34, 0x35, 0xe1, 0x31, 0x1d, 0x1b, 0x06, 0x19,
    /*  48 */ 0x05, 0x11, 0x10, 0x36, 0x37, 0x38, 0xe5, 0x55,
    /*  56 */ 0xe2, 0x2c, 0x39, 0x3a, 0x3b, 0x3c, 0x3d, 0x3e,
    /*  64 */ 0x3f, 0x40, 0x41, 0x42, 0x43, 0x53, 0x47, 0x5f,
    /*  72 */ 0x60, 0x61, 0x56, 0x5c, 0x5d, 0x5e, 0x57, 0x59,
    /*  80 */ 0x5a, 0x5b, 0x62, 0x63, 0x00, 0x94, 0x64, 0x44,
    /*  88 */ 0x45, 0x87, 0x92, 0x93, 0x8a, 0x88, 0x8b, 0x8c,
    /*  96 */ 0x58, 0xe4, 0x54, 0x46, 0xe6, 0x00, 0x4a, 0x52,
    /* 104 */ 0x4b, 0x50, 0x4f, 0x4d, 0x51, 0x4e, 0x49, 0x4c,
    /* 112 */ 0x00, 0x7f, 0x81, 0x80, 0x66, 0x67, 0x00, 0x48,
    /* 120 */ 0x00, 0x85, 0x90, 0x91, 0x89, 0xe3, 0xe7, 0x65
};

uint16_t ghal_hid_from_linux_key(unsigned code)
{
    return code < 128 ? linuxToHid[code] : 0;
}
