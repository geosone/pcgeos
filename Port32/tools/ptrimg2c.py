#!/usr/bin/env python3
"""ptrimg2c.py -- the pointer images of a specific UI in goc.

Reads the PointerImages resource of
Library/SpecUI/CommonUI/CUtils/cutilsVariable.def (PointerDef chunks:
the header, then the mask and image bytes) for one specific UI's
conditions and writes them as @chunk byte arrays of a data resource,
with the table of OpenGetPtrImage (copenUtils.asm: pointerTable) as an
array of chunk names in OLPtrImage order.

usage: ptrimg2c.py cutilsVariable.def copenUtils.asm out.goc [NAME=0|1 ...]
The names default to the Motif build (_MOTIF, _CUA_STYLE).
"""
import re
import sys

DEFAULTS = {
    '_OL_STYLE': 0, '_CUA_STYLE': 1, '_MOTIF': 1, '_ISUI': 0, '_MAC': 0,
    'ANIMATED_BUSY_CURSOR': 0,
}


def cond_value(expr, names):
    """the value of an if expression of names, and, or, not, (0) and (1)"""
    e = expr.split(';')[0].strip()
    e = re.sub(r'\b(\w+)\b',
               lambda m: m.group(1) if m.group(1) in ('and', 'or', 'not', 'eq', 'ne')
               else str(names.get(m.group(1), int(m.group(1))
                                  if m.group(1).isdigit() else 0)), e)
    e = re.sub(r'\beq\b', '==', re.sub(r'\bne\b', '!=', e))
    try:
        return bool(eval(e, {'__builtins__': {}}))
    except SyntaxError:
        return False		# conditions of other parts of the file


def active_lines(path, names):
    """the lines of path whose if/else/endif conditions hold"""
    stack = []
    for line in open(path, encoding='latin-1'):
        s = line.strip()
        word = s.split()[0].lower() if s else ''
        if word == 'if':
            stack.append([cond_value(s[2:], names), False])
            stack[-1][1] = stack[-1][0]
            continue
        if word == 'else':
            top = stack[-1]
            top[0] = not top[1]
            top[1] = True
            continue
        if word == 'endif':
            stack.pop()
            continue
        if all(t[0] for t in stack):
            yield line


def bytes_of(text):
    """the values of byte lists (binary, hex, decimal) in text"""
    out = []
    for tok in re.findall(r'\b[0-9][0-9a-fA-F]*[bhBH]?\b', text):
        if tok[-1] in 'bB' and set(tok[:-1]) <= set('01'):
            out.append(int(tok[:-1], 2))
        elif tok[-1] in 'hH':
            out.append(int(tok[:-1], 16))
        else:
            out.append(int(tok))
    return out


def main():
    var, utils, out = sys.argv[1:4]
    names = dict(DEFAULTS)
    for a in sys.argv[4:]:
        k, v = a.split('=')
        names[k] = int(v)
    lines = list(active_lines(var, names))
    text = ''.join(lines)
    start = text.index('PointerImages\tsegment')
    end = text.index('PointerImages ends')
    text = text[start:end]
    chunks = []
    for m in re.finditer(r'^(\w+)\s+chunk\s*\n(.*?)^\1\s+endc', text,
                         re.S | re.M):
        name, body = m.group(1), m.group(2)
        body = re.sub(r';[^\n]*', '', body)
        hm = re.search(r'PointerDef\s*<(.*?)>', body, re.S)
        fields = [f.strip() for f in hm.group(1).split(',')]
        width = fields[0]
        always = 'PDW_ALWAYS_SHOW_PTR' in width
        w = int(re.search(r'(\d+)\s*$', width).group(1))
        hdr = [w | (0x80 if always else 0), int(fields[1]),
               int(fields[2]) & 0xff, int(fields[3]) & 0xff]
        data = bytes_of(body[hm.end():])
        size = (w + 7) // 8 * int(fields[1])
        assert len(data) == 2 * size, (name, len(data), size)
        chunks.append((name, hdr + data))
    # the table of OpenGetPtrImage
    utext = ''.join(active_lines(utils, names))
    tm = re.search(r'pointerTable\s+label\s+word\s*\n(.*?)\n\s*\n', utext,
                   re.S)
    table = []
    for l in tm.group(1).split('\n'):
        l = l.split(';')[0]
        m = re.search(r'word\s+(?:offset\s+(\w+)|0)', l)
        if m:
            table.append(m.group(1))
    with open(out, 'w') as f:
        f.write('/*\n * cutilsPtrImages.goc -- the pointer images of the '
                'specific UI\n * (PointerImages of cutilsVariable.def) and '
                'the table of\n * OpenGetPtrImage (pointerTable of '
                'copenUtils.asm), for Motif.\n *\n * Generated by '
                'Port32/tools/ptrimg2c.py -- do not edit.\n */\n')
        f.write('@include "cGeode.goh"\n\n@start PointerImages, data;\n\n')
        for name, b in chunks:
            f.write('/* PointerDef: width (PDW_ALWAYS_SHOW_PTR), height, '
                    'hot spot, mask, image */\n' if name == chunks[0][0]
                    else '')
            f.write('@chunk byte %s[] = {\n' % name)
            for i in range(0, len(b), 8):
                f.write('    ' + ', '.join('0x%02x' % v for v in b[i:i + 8])
                        + (',' if i + 8 < len(b) else '') + '\n')
            f.write('};\n\n')
        f.write('@end PointerImages;\n\n')
        f.write('/* OpenGetPtrImage: the PointerDef of an OLPtrImage (OLPI_NONE '
                'and\n * unknown ones: none) */\n')
        f.write('optr OpenGetPtrImage(OLPtrImage image)\n{\n'
                '    switch (image) {\n')
        for i, t in enumerate(table):
            if t is not None:
                f.write('    case %d:\n\treturn @%s;\n' % (i, t))
        f.write('    }\n    return NullOptr;\n}\n')

if __name__ == '__main__':
    main()
