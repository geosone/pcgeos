#!/usr/bin/env python3
"""uiref-gen.py -- the reference application for screen comparisons.

    uiref-gen.py OUTDIR [VARIANT]

Takes the object tree of Port32/Tests/Geode/uiboot.goc (the resources
UBAppObjects and UBAskTemplate) and writes OUTDIR/uiref.goc and uiref.gp:
a plain 16-bit application showing the same objects, to be built with the
original goc and pmake and run in the original GEOS (geosrun.sh with
GEOSRUN_KEEP and a short GEOSRUN_TIMEOUT: the application stays up and the
screen is dumped).  OUTDIR's last component must be "uiref" (pmake names
the geode after the directory).

VARIANT picks what is on the screen:
    1  Doc 1 maximized (texts, gadgets, the spin gadget, sliders) [default]
    2  Doc 2 maximized (items, lists, scrollbar, views, glyphs)
    3  both displays overlapping, as they come up
    4  a standard dialog (an error) over variant 1
    5  Doc 2 maximized, its popup list open
    9  Doc 2 maximized, the down arrow on its closed popup list
    6  the File menu open (a click on its button in the menu bar)
    7  the Tools menu open
    8  the Long menu open
   10  the file selector's dialog over variant 1 (the application makes
       the files it shows: DOCUMENT\\FSTEST)
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "..", "Tests", "Geode", "uiboot.goc")).read()
out = sys.argv[1]
variant = int(sys.argv[2]) if len(sys.argv) > 2 else 1

a = src.index("@start UBAppObjects;")
b = src.index("@end UBAskTemplate;") + len("@end UBAskTemplate;")
tree = src[a:b]
# the test's own classes and messages
tree = tree.replace("@object UBAppClass ", "@object GenApplicationClass ")
tree = tree.replace("@object UBYesClass ", "@object GenTriggerClass ")
tree = tree.replace("@object UBGadgetClass ", "@object URGadgetClass ")
keep = ("MSG_UB_QUERY_ITEM",)
lines = []
for l in tree.split("\n"):
    m = re.search(r"MSG_UB_\w+", l)
    if m and m.group(0) not in keep:
        continue
    lines.append(l)
tree = "\n".join(lines).replace("MSG_UB_QUERY_ITEM", "MSG_UR_QUERY_ITEM")

goc = r'''/*
 * uiref.goc -- generated by Port32/tools/uiref-gen.py from
 * Port32/Tests/Geode/uiboot.goc: the objects of the UI boot test in a
 * plain application for the original (16-bit) GEOS, to compare screens.
 * Variant %(variant)d.
 */
@include <stdapp.goh>
@include <Objects/gValueC.goh>
@include <Objects/gDListC.goh>
@include <Objects/gGadgetC.goh>
@include <Objects/vTextC.goh>
@include <Objects/gFSelC.goh>
#include <file.h>
#include <uDialog.h>

@class URProcessClass, GenProcessClass;
    @message (GEN_DYNAMIC_LIST_QUERY_MSG) MSG_UR_QUERY_ITEM;
    @message void MSG_UR_SHOW();
@endc
@classdecl URProcessClass, neverSaved;

@class URGadgetClass, GenGadgetClass;
@endc
@classdecl URGadgetClass;

@method URGadgetClass, MSG_VIS_RECALC_SIZE
{
    return MAKE_SIZE_DWORD(30, 20);
}

@method URGadgetClass, MSG_VIS_DRAW
{
    Rectangle r;

    @call oself::MSG_VIS_GET_BOUNDS(&r);
    GrSetAreaColor(gstate, CF_INDEX, C_BLUE, 0, 0);
    GrFillRect(gstate, r.R_left, r.R_top, r.R_right, r.R_bottom);
}

%(tree)s

@method URProcessClass, MSG_UR_QUERY_ITEM
{
    char t[12] = "Item ", *p = t + 5;

    if (item >= 10)
	*p++ = (char) ('0' + item / 10 %% 10);
    *p++ = (char) ('0' + item %% 10);
    *p = 0;
    @call list::MSG_GEN_DYNAMIC_LIST_REPLACE_ITEM_TEXT(item, t);
}

@method URProcessClass, MSG_GEN_PROCESS_OPEN_APPLICATION
{
    @callsuper();
    @send, forceQueue oself::MSG_UR_SHOW();
}

/* a click on the n-th button of the primary's menu bar: the bar is the
 * child of the primary that is no generic object and whose children
 * are none either */
static void URClickMenu(word n)
{
    optr bar = 0, c, b;
    word i;
    Rectangle r;
    MouseReturnParams mr;

    for (i = 0; (c = @call UBPrimary::MSG_VIS_FIND_CHILD_AT_POSITION(i)) != 0;
	 i++) {
	if (@call c::MSG_META_IS_OBJECT_IN_CLASS(&GenClass))
	    continue;
	b = @call c::MSG_VIS_FIND_CHILD_AT_POSITION(0);
	if (b && !@call b::MSG_META_IS_OBJECT_IN_CLASS(&GenClass)) {
	    bar = c;
	    break;
	}
    }
    if (!bar || (b = @call bar::MSG_VIS_FIND_CHILD_AT_POSITION(n)) == 0)
	return;
    @call b::MSG_VIS_GET_BOUNDS(&r);
    /* both queued, so that the objects' thread handles them one after
     * the other: with two calls it gets to a pointer event of the real
     * mouse in between (the menu coming up makes one), the button
     * gives up its mouse grab and the release does nothing */
    @send, forceQueue b::MSG_META_START_SELECT(&mr, r.R_left + 3, r.R_top + 3,
		((UIFA_SELECT | UIFA_IN) << 8) | BI_PRESS | BI_B0_DOWN);
    @send, forceQueue b::MSG_META_END_SELECT(&mr, r.R_left + 3, r.R_top + 3,
		UIFA_IN << 8);
    @call UBPrimary::MSG_GEN_UPDATE_VISUAL(VUM_NOW);
}

@method URProcessClass, MSG_UR_SHOW
{
#if %(variant)d == 1 || %(variant)d == 4 || %(variant)d == 10
    @call UBDoc1::MSG_GEN_BRING_TO_TOP();
    @call UBDoc1::MSG_GEN_DISPLAY_SET_MAXIMIZED();
#endif
#if %(variant)d == 2
    @call UBDoc2::MSG_GEN_BRING_TO_TOP();
    @call UBDoc2::MSG_GEN_DISPLAY_SET_MAXIMIZED();
#endif
#if %(variant)d == 5 || %(variant)d == 9
    {
	/* the popup list opened: space on its button, the one child of
	 * the list's row that is no generic object */
	optr p, c;
	word i;

	@call UBDoc2::MSG_GEN_BRING_TO_TOP();
	@call UBDoc2::MSG_GEN_DISPLAY_SET_MAXIMIZED();
	@call UBDoc2::MSG_GEN_UPDATE_VISUAL(VUM_NOW);
	p = @call UBChecks::MSG_VIS_FIND_PARENT();
	for (i = 0; p && (c = @call p::MSG_VIS_FIND_CHILD_AT_POSITION(i)) != 0;
	     i++)
	    if (!@call c::MSG_META_IS_OBJECT_IN_CLASS(&GenClass)) {
#if %(variant)d == 9
		@call c::MSG_META_KBD_CHAR((VC_ISCTRL << 8) | VC_DOWN,
					   CF_FIRST_PRESS, 0);
#else
		@call c::MSG_META_KBD_CHAR(VC_BLANK, CF_FIRST_PRESS, 0);
#endif
		break;
	    }
    }
#endif
#if %(variant)d >= 6 && %(variant)d <= 8
    @call UBDoc1::MSG_GEN_BRING_TO_TOP();
    @call UBDoc1::MSG_GEN_DISPLAY_SET_MAXIMIZED();
    @call UBPrimary::MSG_GEN_UPDATE_VISUAL(VUM_NOW);
    URClickMenu(%(variant)d - 6);
#endif
#if %(variant)d == 10
    {
	static const char *files[] = { "ALPHA.TXT", "BETA.TXT" };
	FileHandle fh;
	word i;

	FilePushDir();
	FileSetCurrentPath(SP_DOCUMENT, ".");
	(void) FileCreateDir("FSTEST");
	FileSetCurrentPath(SP_DOCUMENT, "FSTEST");
	(void) FileCreateDir("LETTERS");
	for (i = 0; i < 2; i++) {
	    fh = FileCreate(files[i], FILE_CREATE_TRUNCATE | FCF_NATIVE |
			    FILE_ACCESS_W | FILE_DENY_RW, 0);
	    if (fh)
		FileClose(fh, FALSE);
	}
	FilePopDir();
	(void) @call UBFSel::MSG_GEN_PATH_SET("FSTEST", SP_DOCUMENT);
	@call UBFiles::MSG_GEN_INTERACTION_INITIATE();
    }
#endif
#if %(variant)d == 4
    (void) UserStandardDialog(NULL, NULL, NULL, "42", "Error \001 happened.",
		(CDT_ERROR << CDBF_DIALOG_TYPE_OFFSET) |
		(GIT_NOTIFICATION << CDBF_INTERACTION_TYPE_OFFSET));
#endif
}
''' % {"variant": variant, "tree": tree}

gp = '''# uiref.gp -- generated by Port32/tools/uiref-gen.py
name     uiref.app
longname "UI Reference"
tokenchars "UIRF"
tokenid    0
type	appl, process, single
class	URProcessClass
appobj	UBApp
heapspace 4000
library	geos
library	ui
library text
resource UBAppObjects ui-object
resource UBAskTemplate ui-object
export URGadgetClass
'''
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "uiref.goc"), "w").write(goc)
open(os.path.join(out, "uiref.gp"), "w").write(gp)
