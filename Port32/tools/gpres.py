#!/usr/bin/env python3
"""gpres.py -- resource numbers of a geode for C code made by goc -cg.

Usage:  gpres.py [-o OUT.h] GEODE.gp [FILE.goc...]

goc -cg refers to the resources of a geode as GOCR_RES_<NAME> (the name in
upper case).  This script numbers them like glue does: first the
"resource" lines of the geode parameter file in their order, then the
resources the .goc files start (@start) but the .gp file does not list, in
the order of the files and of their @start lines.  Numbers start at 2 (0 is
the core block, 1 the fixed data, as in the 16-bit geode format).  The
header goes to OUT.h or to standard output.  See Port32/ABI.md.
"""
import re
import sys

FIRST = 2


def gp_resources(text):
    names = []
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        m = re.match(r'resource\s+(\S+)', line, re.IGNORECASE)
        if m:
            names.append(m.group(1))
    return names


def goc_resources(text):
    # @start Name[, flags];  (not inside comments: good enough for goc files)
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.DOTALL)
    return re.findall(r'^\s*@start\s+(\w+)', text, re.MULTILINE)


def main():
    args = sys.argv[1:]
    out = None
    if len(args) >= 2 and args[0] == '-o':
        out, args = args[1], args[2:]
    if not args or not args[0].lower().endswith('.gp'):
        sys.exit(__doc__)
    names = []
    for i, path in enumerate(args):
        with open(path, encoding='latin-1') as f:
            text = f.read()
        found = gp_resources(text) if i == 0 else goc_resources(text)
        for name in found:
            if name.upper() not in names:
                names.append(name.upper())
    lines = ['/* generated by Port32/tools/gpres.py from '
             + ' '.join(p.rsplit('/', 1)[-1] for p in args) + ' */']
    for i, name in enumerate(names):
        lines.append(f'#define GOCR_RES_{re.sub(r"[^A-Za-z0-9_]", "_", name)} {FIRST + i}')
    text = '\n'.join(lines) + '\n'
    if out:
        with open(out, 'w') as f:
            f.write(text)
    else:
        sys.stdout.write(text)


if __name__ == '__main__':
    main()
