#!/usr/bin/env python3
"""kexports.py -- the export table of the C kernel ("geos" library).

A geode imports kernel routines and classes by name (Port32/ABI.md
section 7).  The kernel exports what Library/Kernel/geos.gp exports and
the C kernel defines: the global symbols of the kernel's object files
(from nm) whose names match an export of geos.gp, ignoring case (the
.gp file lists the asm names and the upper-case C stubs; the C kernel
defines the C names).  Port32 adds the C entry points that have no asm
counterpart (PORT32_EXPORTS) and the GHAL host services for drivers
(GHAL_EXPORTS, defined in the ghal library), and the four routines a C
compiler may call on its own even in a freestanding geode, for structure
copies and zeroing (COMPILER_EXPORTS, from the host's C library).

Writes a C file with kernelExports[], sorted by name for a binary
search, and kernelExportCount.  Each entry carries its entry number in
geos.gp (exports and "skip" counted as glue does; the Port32 extras get
0x8000 + n): references to kernel entries in files use it, so it stays
the same when the C kernel defines more of them (Port32/ABI.md 13d).

usage: kexports.py --nm NM --gp geos.gp [--underscore] [--extra NAME]...
                   -o out.c object...
"""
import argparse
import re
import subprocess
import sys

# C entry points of Port32 without an asm export (Port32/ABI.md section 5)
PORT32_EXPORTS = [
    "CObjMessageP", "CObjCallSuperP", "CMessageDispatchP",
]
# more of them, numbered after the lists below (their entry numbers stay)
PORT32_LATE_EXPORTS = [
    "GrLoadGStringPtr", "ThreadPrivData",
]
# GHAL host services the drivers on the GHAL use (Port32/GHAL-Concept.md
# section 4, level 2): exported always, as they live in the ghal library
# beside the kernel.  New names go at the end (their entry numbers).
GHAL_EXPORTS = [
    "ghal_crit_enter", "ghal_crit_leave", "ghal_log",
    "ghal_time_monotonic_ns",
    "ghal_irq_attach", "ghal_irq_detach", "ghal_irq_active",
    "ghal_input_read", "ghal_input_post", "ghal_input_dropped",
    "ghal_display_open", "ghal_display_flush", "ghal_display_close",
    "ghal_display_close_requested", "ghal_display_read_back",
    "ghal_display_backend",
]

# gcc and clang require these of a freestanding environment
COMPILER_EXPORTS = ["memcpy", "memmove", "memset", "memcmp"]

GP_EXPORT = re.compile(r"^\s*(export|publish)\s+(\S+)(?:\s+as\s+(\S+))?",
                       re.I)
GP_SKIP = re.compile(r"^\s*skip\s+(\d+)", re.I)


def gp_names(path):
    """upper-case name -> entry number"""
    names = {}
    n = 0
    with open(path, encoding="latin-1") as f:
        for line in f:
            line = line.split("#", 1)[0]
            m = GP_EXPORT.match(line)
            if m:
                names.setdefault(m.group(2).upper(), n)
                if m.group(3):
                    names.setdefault(m.group(3).upper(), n)
                n += 1
                continue
            m = GP_SKIP.match(line)
            if m:
                n += int(m.group(1))
    return names


def defined_symbols(nm, objects, underscore):
    out = subprocess.run([nm, "-g", "--defined-only"] + objects,
                         check=True, capture_output=True, text=True).stdout
    syms = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        kind, name = parts[1], parts[2]
        if kind not in "TDRBCGS":
            continue
        if underscore:
            if not name.startswith("_"):
                continue
            name = name[1:]
        syms[name] = kind
    return syms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nm", required=True)
    ap.add_argument("--gp", required=True)
    ap.add_argument("--underscore", action="store_true",
                    help="C names have a leading underscore (COFF)")
    ap.add_argument("--extra", action="append", default=[])
    ap.add_argument("-o", dest="out", required=True)
    ap.add_argument("objects", nargs="+")
    a = ap.parse_args()

    wanted = gp_names(a.gp)
    extra = PORT32_EXPORTS + [e for e in a.extra if e not in PORT32_EXPORTS]
    syms = defined_symbols(a.nm, a.objects, a.underscore)
    names = [n for n in syms if n.upper() in wanted or n in extra or
             n in PORT32_LATE_EXPORTS]
    extra += [g for g in GHAL_EXPORTS + COMPILER_EXPORTS + PORT32_LATE_EXPORTS
              if g not in extra]
    names = sorted(set(names) | set(GHAL_EXPORTS) | set(COMPILER_EXPORTS))

    with open(a.out, "w") as f:
        f.write("/* generated by Port32/tools/kexports.py -- do not edit */\n")
        f.write("typedef struct { const char *name; const void *addr; "
                "unsigned short entry; } KernelExport;\n\n")
        f.write("#include <string.h>\n")
        for n in names:
            if n not in COMPILER_EXPORTS:
                f.write("extern char %s;\n" % n)
        f.write("\nconst KernelExport kernelExports[] = {\n")
        for n in names:
            entry = wanted.get(n.upper())
            if entry is None:
                entry = 0x8000 + extra.index(n)
            addr = ("(const void *) %s" if n in COMPILER_EXPORTS
                    else "&%s") % n
            f.write('    { "%s", %s, 0x%04x },\n' % (n, addr, entry))
        if not names:
            f.write("    { 0, 0, 0 }\n")
        f.write("};\n")
        f.write("const unsigned kernelExportCount = %d;\n" % len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
