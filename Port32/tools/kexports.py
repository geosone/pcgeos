#!/usr/bin/env python3
"""kexports.py -- the export table of the C kernel ("geos" library).

A geode imports kernel routines and classes by name (Port32/ABI.md
section 7).  The kernel exports what Library/Kernel/geos.gp exports and
the C kernel defines: the global symbols of the kernel's object files
(from nm) whose names match an export of geos.gp, ignoring case (the
.gp file lists the asm names and the upper-case C stubs; the C kernel
defines the C names).  Port32 adds the C entry points that have no asm
counterpart (PORT32_EXPORTS).

Writes a C file with kernelExports[], sorted by name for a binary
search, and kernelExportCount.

usage: kexports.py --nm NM --gp geos.gp [--underscore] [--extra NAME]...
                   -o out.c object...
"""
import argparse
import re
import subprocess
import sys

# C entry points of Port32 without an asm export (Port32/ABI.md section 5)
PORT32_EXPORTS = [
    "CObjMessageP", "CObjCallSuperP", "CMessageDispatchP",
]

GP_EXPORT = re.compile(r"^\s*(export|publish)\s+(\S+)(?:\s+as\s+(\S+))?",
                       re.I)


def gp_names(path):
    names = set()
    with open(path, encoding="latin-1") as f:
        for line in f:
            line = line.split("#", 1)[0]
            m = GP_EXPORT.match(line)
            if m:
                names.add(m.group(2).upper())
                if m.group(3):
                    names.add(m.group(3).upper())
    return names


def defined_symbols(nm, objects, underscore):
    out = subprocess.run([nm, "-g", "--defined-only"] + objects,
                         check=True, capture_output=True, text=True).stdout
    syms = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        kind, name = parts[1], parts[2]
        if kind not in "TDRBCGS":
            continue
        if underscore:
            if not name.startswith("_"):
                continue
            name = name[1:]
        syms[name] = kind
    return syms


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nm", required=True)
    ap.add_argument("--gp", required=True)
    ap.add_argument("--underscore", action="store_true",
                    help="C names have a leading underscore (COFF)")
    ap.add_argument("--extra", action="append", default=[])
    ap.add_argument("-o", dest="out", required=True)
    ap.add_argument("objects", nargs="+")
    a = ap.parse_args()

    wanted = gp_names(a.gp)
    extra = set(PORT32_EXPORTS + a.extra)
    syms = defined_symbols(a.nm, a.objects, a.underscore)
    names = sorted(n for n in syms
                   if n.upper() in wanted or n in extra)

    with open(a.out, "w") as f:
        f.write("/* generated by Port32/tools/kexports.py -- do not edit */\n")
        f.write("typedef struct { const char *name; const void *addr; } "
                "KernelExport;\n\n")
        for n in names:
            f.write("extern char %s;\n" % n)
        f.write("\nconst KernelExport kernelExports[] = {\n")
        for n in names:
            f.write('    { "%s", &%s },\n' % (n, n))
        if not names:
            f.write("    { 0, 0 }\n")
        f.write("};\n")
        f.write("const unsigned kernelExportCount = %d;\n" % len(names))
    return 0


if __name__ == "__main__":
    sys.exit(main())
